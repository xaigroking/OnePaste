//! macOS clipboard: the system sends no change notification, so `changeCount` is polled every 300 ms.

use crate::clipboard::{classify, Content, Event, Image, Snapshot, WriteOptions};
use crate::error::PlatformError;
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardTypePNG, NSPasteboardTypeString,
    NSPasteboardTypeTIFF,
};
use objc2_foundation::{NSData, NSDictionary, NSString};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::thread::JoinHandle;
use std::time::Duration;

const TYPE_ORIGIN: &str = "dev.onepaste.origin";
const TYPE_CONCEALED: &str = "org.nspasteboard.ConcealedType";
const TYPE_TRANSIENT: &str = "org.nspasteboard.TransientType";
const TYPE_AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
const POLL_INTERVAL: Duration = Duration::from_millis(300);

fn snapshot(pb: &NSPasteboard) -> Snapshot {
    let types: Vec<String> = match pb.types() {
        Some(arr) => arr.iter().map(|t| t.to_string()).collect(),
        None => Vec::new(),
    };
    let has = |name: &str| types.iter().any(|t| t == name);
    let from_self = has(TYPE_ORIGIN);
    if has(TYPE_CONCEALED) || has(TYPE_TRANSIENT) || has(TYPE_AUTO_GENERATED) {
        return Snapshot { content: None, sensitive: true, from_self };
    }
    Snapshot { content: read_content(pb, &types), sensitive: false, from_self }
}

fn read_content(pb: &NSPasteboard, types: &[String]) -> Option<Content> {
    let has = |name: &str| types.iter().any(|t| t == name);
    if has("public.utf8-plain-text") {
        let s = unsafe { pb.stringForType(NSPasteboardTypeString) }?.to_string();
        return if s.is_empty() { None } else { Some(Content::Text(s)) };
    }
    if has("public.png") {
        let data = unsafe { pb.dataForType(NSPasteboardTypePNG) }?;
        let png = data.to_vec();
        let (width, height) = crate::png_info::dimensions(&png)?;
        return Some(Content::Image(Image { png, width, height }));
    }
    if has("public.tiff") {
        let tiff = unsafe { pb.dataForType(NSPasteboardTypeTIFF) }?;
        let rep = NSBitmapImageRep::imageRepWithData(&tiff)?;
        let png = unsafe { rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new()) }?
            .to_vec();
        let (width, height) = crate::png_info::dimensions(&png)?;
        return Some(Content::Image(Image { png, width, height }));
    }
    None
}

pub(crate) fn read() -> Result<Snapshot, PlatformError> {
    Ok(snapshot(&NSPasteboard::generalPasteboard()))
}

fn set_marker(pb: &NSPasteboard, name: &str) -> Result<(), PlatformError> {
    let ok = pb.setData_forType(Some(&NSData::with_bytes(&[1])), &NSString::from_str(name));
    if ok {
        Ok(())
    } else {
        Err(PlatformError::Os(-1))
    }
}

pub(crate) fn write(content: &Content, opts: WriteOptions) -> Result<(), PlatformError> {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    let ok = match content {
        Content::Text(s) => unsafe { pb.setString_forType(&NSString::from_str(s), NSPasteboardTypeString) },
        Content::Image(i) => unsafe { pb.setData_forType(Some(&NSData::with_bytes(&i.png)), NSPasteboardTypePNG) },
    };
    if !ok {
        return Err(PlatformError::Os(-1));
    }
    if opts.origin_marker {
        set_marker(&pb, TYPE_ORIGIN)?;
    }
    if opts.sensitive_marker {
        set_marker(&pb, TYPE_CONCEALED)?;
    }
    Ok(())
}

pub(crate) struct Monitor {
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}

impl Monitor {
    pub(crate) fn start(on_event: Box<dyn Fn(Event) + Send>) -> Result<Monitor, PlatformError> {
        let stop = Arc::new(AtomicBool::new(false));
        let flag = stop.clone();
        // The starting point is taken synchronously on the calling thread so writes before the thread starts are neither missed nor misreported.
        let mut last = NSPasteboard::generalPasteboard().changeCount();
        let thread = std::thread::spawn(move || {
            let pb = NSPasteboard::generalPasteboard();
            while !flag.load(Ordering::Relaxed) {
                std::thread::sleep(POLL_INTERVAL);
                let now = pb.changeCount();
                if now != last {
                    last = now;
                    if let Some(ev) = classify(snapshot(&pb)) {
                        on_event(ev);
                    }
                }
            }
        });
        Ok(Monitor { stop, thread: Some(thread) })
    }
}

impl Drop for Monitor {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
        if let Some(t) = self.thread.take() {
            let _ = t.join();
        }
    }
}
